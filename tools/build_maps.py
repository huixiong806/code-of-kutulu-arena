"""Extract the 20 maze definitions from the Java referee into a JS module.

Read-only with respect to the parent project: it only parses
build/java/codeofkutulu/mazes/*.java and writes arena/server/game/maps.js.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "build/java/codeofkutulu/mazes"
OUT = Path(__file__).resolve().parents[1] / "server/game/maps.js"

mazes = []
for path in sorted(SRC.glob("*.java")):
    name = path.stem
    if name in ("Maze", "MazeFactory"):
        continue
    text = path.read_text(encoding="utf8")
    m = re.search(r"String\[\]\s+map\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        continue
    rows = re.findall(r'"([^"]*)"', m.group(1))
    title = re.search(r'super\("([^"]+)"\)', text)
    mazes.append({"key": name, "name": title.group(1) if title else name, "rows": rows})

lits = []
for maze in mazes:
    body = ",\n    ".join('"%s"' % r for r in maze["rows"])
    lits.append("  {\n    name: %s,\n    rows: [\n    %s\n    ]\n  }" % (json.dumps(maze["name"]), body))

js = (
    "// Generated by tools/build_maps.py from build/java/codeofkutulu/mazes/*.java\n"
    "// Legend league plays the full 16-map pool (MazeFactory.bronzeMaps).\n"
    "export const ALL_MAPS = [\n" + ",\n".join(lits) + "\n];\n\n"
    "export const WOOD_MAPS = ['Pac man','Hypersonic','Oasis','Corridors','Origin of symmetry','Four of a kind'];\n"
)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(js, encoding="utf8")
print(f"wrote {len(mazes)} maps -> {OUT}")
for m in mazes:
    print(f"  {m['name']:<26} {len(m['rows'])}x{len(m['rows'][0])}")
